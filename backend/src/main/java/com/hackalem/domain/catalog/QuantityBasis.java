package com.hackalem.domain.catalog;

/**
 * Почему у агрегированного остатка есть или нет числа.
 * Склады не складываются без политики fulfillment (её задаёт CAT-03), поэтому
 * число отдаётся только когда доступен ровно один склад с известным количеством.
 */
public enum QuantityBasis {
    /** Один доступный склад с известным количеством — число отдаётся. */
    SINGLE_WAREHOUSE,
    /** Несколько доступных складов: не объединяем, число не отдаём. */
    MULTIPLE_WAREHOUSES_NOT_MERGED,
    /** Хотя бы один доступный склад с неизвестным количеством. */
    UNKNOWN,
    /** Нет складов, доступных для отгрузки. */
    NO_ELIGIBLE_WAREHOUSE
}
