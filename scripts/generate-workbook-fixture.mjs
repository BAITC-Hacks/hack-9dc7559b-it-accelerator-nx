import fs from 'node:fs/promises';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const root = process.argv[2] ?? process.cwd();
const rows = JSON.parse(await fs.readFile(`${root}/data/expected/attachment-rows.json`, 'utf8')).rows;
const wb = Workbook.create();
const sheet = wb.worksheets.add('Specification');
sheet.showGridLines = false;
sheet.getRange('A1:E4').values = [['Артикул','Описание','Количество','Единица','Цена'], ...rows.map((r,i)=>[r.article,r.description,r.quantity ? Number(r.quantity) : null,r.unit,i===0?1500:i===1?2700:null])];
sheet.getRange('A1:E4').format.font = {name:'Arial',size:11};
sheet.getRange('A1:E1').format.fill = '#24415c';
sheet.getRange('A1:E1').format.font = {name:'Arial',size:11,bold:true,color:'#ffffff'};
sheet.getRange('A1:A4').setNumberFormat('@');
sheet.getRange('C2:C4').setNumberFormat('0.0');
sheet.getRange('A1:E4').format.autofitColumns();
sheet.getRange('A1:A4').format.columnWidth = 14;
sheet.getRange('B1:B4').format.columnWidth = 38;
sheet.getRange('C1:E4').format.columnWidth = 17;
sheet.getRange('A1:E4').format.rowHeight = 25;
sheet.getRange('G1').values = [['SYNTHETIC FIXTURE']];
sheet.getRange('G1').format.columnWidth = 28;
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'Specification!A1:E4',include:'values,formulas',tableMaxRows:4,tableMaxCols:5})).ndjson);
await fs.mkdir(`${root}/data/attachments/office`,{recursive:true});
await (await SpreadsheetFile.exportXlsx(wb)).save(`${root}/data/attachments/office/specification.xlsx`);
const preview=await wb.render({sheetName:'Specification',range:'A1:G5',scale:1.5,format:'png'});
if (process.argv[3]) await fs.writeFile(process.argv[3],new Uint8Array(await preview.arrayBuffer()));
